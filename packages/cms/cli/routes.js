import { existsSync } from 'node:fs'
import { mkdir, readdir, readFile, rm, rmdir, writeFile } from 'node:fs/promises'
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path'
import { CliError } from './migrations.js'

// First line of every file the command owns: it rewrites or deletes only files that start with it.
export const MARKER = '// Generated by linkchar-cms routes: change cms.config.ts and run it again instead of editing this file.'

// The server actions the panel calls from the browser, re-exported by src/cms/actions.ts (a test keeps it in sync).
export const ACTION_NAMES = [
  'saveDocument', 'createDocument', 'createRelated', 'duplicateDocument', 'trashDocument', 'setDocumentVisibility', 'reorderCollection',
  'listVersions', 'getVersionDiff', 'restoreVersion', 'discardChanges', 'restoreDocument', 'purgeDocument', 'searchRelation',
  'registerMedia', 'updateMedia', 'getMediaUsage', 'trashMedia', 'restoreMedia', 'purgeMedia', 'searchMedia',
  'publishChanges', 'getPublishStatus',
  'inviteUser', 'updateUserAccess', 'setUserActive', 'resendInvite', 'deleteInvite', 'resetUserMfa',
  'updateProfile', 'updateAvatar', 'changePassword', 'recordMfaChange', 'markTourSeen', 'resetTours',
  'login', 'requestPasswordReset', 'updatePassword', 'acceptInvite', 'completeSecondFactor', 'logout'
]

/** @typedef {{ basePath: string, paths: Record<string, string> }} RoutesConfigType */
/** @typedef {'page' | 'layout'} ViewKindType */
/**
 * @typedef {{ file: string, managed: boolean, render: (importOf: (target: string) => string) => string }} RouteFileType
 * @typedef {{ file: string, status: 'added' | 'updated' | 'removed' | 'same' | 'kept' }} RouteChangeType
 */

/** @param {string} module @param {string} factory @param {ViewKindType} kind @param {string[]} [extra] */
const view = (module, factory, kind, extra = []) => /** @param {(target: string) => string} importOf */ importOf => [
  `import { ${factory} } from '@linkcharsoft/cms/panel/routes/${module}'`,
  `import { cms } from '${importOf('cms/server')}'`,
  '',
  `const route = ${factory}(cms)`,
  '',
  `export default route.${kind === 'page' ? 'Page' : 'Layout'}`,
  ...extra.map(name => `export const ${name} = route.${name}`)
].join('\n')

/** @param {string} method @param {string} handler */
const handler = (method, handler) => /** @param {(target: string) => string} importOf */ importOf => [
  `import { cms } from '${importOf('cms/server')}'`,
  '',
  `export const ${method} = cms.handlers.${handler}`
].join('\n')

const loading = () => 'export { default } from \'@linkcharsoft/cms/panel/routes/loading\''

/**
 * Every file of the panel wiring, relative to the project's source folder (src/ or the root).
 * @param {RoutesConfigType} config
 * @param {string} configFile absolute path of cms.config.ts
 * @returns {RouteFileType[]}
 */
export const planRoutes = ({ basePath, paths }, configFile) => {
  const base = join('app', '(cms)', ...basePath.split('/').filter(Boolean))
  const auth = join(base, '(auth)')
  const panel = join(base, '(panel)')
  const workspace = join(panel, '(workspace)')
  const admin = join(panel, '(admin)')

  /** @type {[string, (importOf: (target: string) => string) => string][]} */
  const managed = [
    [join(auth, 'layout.tsx'), view('auth', 'authLayout', 'layout')],
    [join(auth, paths.login, 'page.tsx'), view('login', 'loginRoute', 'page', ['metadata'])],
    [join(auth, paths.passwordRecovery, 'page.tsx'), view('password-recovery', 'passwordRecoveryRoute', 'page', ['metadata'])],
    [join(auth, paths.passwordReset, 'page.tsx'), view('password-reset', 'passwordResetRoute', 'page', ['metadata'])],
    [join(auth, paths.acceptInvite, 'page.tsx'), view('accept-invite', 'acceptInviteRoute', 'page', ['metadata'])],
    [join(auth, paths.mfaVerify, 'page.tsx'), view('mfa-verify', 'mfaVerifyRoute', 'page', ['metadata'])],
    [join(base, 'auth', 'confirm', 'route.ts'), handler('GET', 'authConfirm')],
    [join(base, 'auth', 'signout', 'route.ts'), handler('GET', 'signout')],
    [join(panel, 'layout.tsx'), view('panel', 'panelLayout', 'layout')],
    [join(workspace, 'loading.tsx'), loading],
    [join(admin, 'layout.tsx'), view('admin', 'adminLayout', 'layout')],
    [join(admin, 'loading.tsx'), loading],
    [join('app', 'api', 'cms', 'build-status', 'route.ts'), handler('POST', 'buildStatus')],
    [join('cms', 'actions.ts'), () => ['\'use server\'', 'import { cms } from \'./server\'', '', ...ACTION_NAMES.map(name => `export const ${name} = cms.actions.${name}`)].join('\n')]
  ]

  // Created once and then owned by the project: the theme CSS, fonts and custom inputs go there.
  /** @type {[string, (importOf: (target: string) => string) => string][]} */
  const scaffolds = [
    [join('app', '(cms)', 'layout.tsx'), importOf => [
      'import { rootLayout } from \'@linkcharsoft/cms/panel/routes/root\'',
      `import { CmsClient } from '${importOf('cms/client')}'`,
      `import { cms } from '${importOf('cms/server')}'`,
      '',
      'const route = rootLayout(cms, CmsClient)',
      '',
      'export default route.Layout',
      'export const metadata = route.metadata'
    ].join('\n')],
    [join('cms', 'client.ts'), importOf => [
      '\'use client\'',
      'import { createCmsClient } from \'@linkcharsoft/cms/panel/client\'',
      `import cmsConfig from '${importOf(configFile.replace(/\.[cm]?[jt]s$/, ''))}'`,
      'import * as actions from \'./actions\'',
      '',
      'export const CmsClient = createCmsClient({ config: cmsConfig, actions, inputs: {} })'
    ].join('\n')]
  ]

  return [
    ...managed.map(([file, render]) => ({ file, managed: true, render })),
    ...scaffolds.map(([file, render]) => ({ file, managed: false, render }))
  ]
}

const toPosix = (/** @type {string} */ path) => path.split(sep).join('/')

/** @param {string} from @param {string} target */
const importPath = (from, target) => {
  const path = toPosix(relative(dirname(from), target))
  return path.startsWith('.') ? path : `./${path}`
}

/** @param {string} dir @returns {Promise<string[]>} */
const walk = async dir => {
  if (!existsSync(dir)) return []
  const entries = await readdir(dir, { withFileTypes: true })
  const nested = await Promise.all(entries.map(entry => (entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)])))
  return nested.flat()
}

/** @param {string} dir @param {string} stop */
const removeEmptyDirs = async (dir, stop) => {
  let current = dir
  while (current.startsWith(stop) && current !== stop && existsSync(current) && (await readdir(current)).length === 0) {
    await rmdir(current)
    current = dirname(current)
  }
}

const sameText = (/** @type {string} */ a, /** @type {string} */ b) => a.replace(/\r\n/g, '\n') === b.replace(/\r\n/g, '\n')

/**
 * Writes the managed files, creates the missing scaffolds and removes managed files the config no longer has.
 * Files without the marker belong to the project and are never touched.
 * @param {{ sourceDir: string, config: RoutesConfigType, configFile: string, write?: boolean }} options
 * @returns {Promise<RouteChangeType[]>}
 */
export const syncRoutes = async ({ sourceDir, config, configFile, write = true }) => {
  const planned = planRoutes(config, configFile)
  /** @type {RouteChangeType[]} */
  const changes = []

  for (const { file, managed, render } of planned) {
    const path = join(sourceDir, file)
    const body = render(target => importPath(path, isAbsolute(target) ? target : join(sourceDir, target)))
    const content = `${managed ? `${MARKER}\n` : ''}${body}\n`
    const current = existsSync(path) ? await readFile(path, 'utf8') : null

    if (current !== null && (!managed || !current.startsWith(MARKER))) {
      changes.push({ file: toPosix(file), status: 'kept' })
      continue
    }
    const status = current === null ? 'added' : sameText(current, content) ? 'same' : 'updated'
    if (status !== 'same' && write) {
      await mkdir(dirname(path), { recursive: true })
      await writeFile(path, content)
    }
    changes.push({ file: toPosix(file), status })
  }

  const plannedPaths = new Set(planned.map(({ file }) => join(sourceDir, file)))
  const panelDir = join(sourceDir, 'app', '(cms)')
  for (const path of await walk(panelDir)) {
    if (plannedPaths.has(path) || !(await readFile(path, 'utf8')).startsWith(MARKER)) continue
    if (write) {
      await rm(path)
      await removeEmptyDirs(dirname(path), panelDir)
    }
    changes.push({ file: toPosix(relative(sourceDir, path)), status: 'removed' })
  }

  return changes
}

/**
 * The proxy matcher must be a literal (Next reads it statically), so it is checked instead of generated.
 * @param {{ sourceDir: string, basePath: string }} options
 * @returns {Promise<'ok' | 'missing' | 'stale'>}
 */
export const checkProxy = async ({ sourceDir, basePath }) => {
  const file = ['proxy.ts', 'proxy.js'].map(name => join(sourceDir, name)).find(path => existsSync(path))
  if (!file) return 'missing'
  return (await readFile(file, 'utf8')).includes(`'${basePath}/:path*'`) ? 'ok' : 'stale'
}

/** @param {string} root */
const tsconfigAliases = async root => {
  const file = join(root, 'tsconfig.json')
  if (!existsSync(file)) return {}
  const text = (await readFile(file, 'utf8')).replace(/^\s*\/\/.*$/gm, '')
  /** @type {Record<string, string[]>} */
  const paths = JSON.parse(text).compilerOptions?.paths ?? {}
  return Object.fromEntries(Object.entries(paths)
    .filter(([key, targets]) => key.endsWith('/*') && targets[0]?.endsWith('/*'))
    .map(([key, targets]) => [key.slice(0, -1), `${resolve(root, targets[0].slice(0, -1))}/`]))
}

/**
 * cms.config.ts imports the package's TypeScript source, which Node won't strip inside node_modules: jiti loads it.
 * @param {string} file
 * @returns {Promise<RoutesConfigType>}
 */
export const loadConfig = async file => {
  if (!existsSync(file)) throw new CliError(`There is no CMS config at ${file}: pass --config.`)
  const { createJiti } = await import('jiti')
  const jiti = createJiti(import.meta.url, { alias: await tsconfigAliases(dirname(file)), moduleCache: false })
  const config = /** @type {RoutesConfigType | undefined} */ (await jiti.import(file, { default: true }))
  if (!config?.basePath || !config.paths) throw new CliError(`${file} must export defineCmsConfig(...) as default.`)
  return config
}
