import { existsSync } from 'node:fs'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'

export const KEEPALIVE_FILE = '.github/workflows/supabase-keepalive.yml'

export const KEEPALIVE_MARKER = '# Generated by linkchar-cms routes: run it again instead of editing this file.'

// One read every three days: Supabase pauses a free project after a week without requests, and a paused project
// has no panel and no builds. The repository variables are the ones the CI build already needs.
export const keepaliveWorkflow = () => [
  KEEPALIVE_MARKER,
  '# A free Supabase project pauses after a week without requests; this read keeps it awake.',
  'name: Supabase keepalive',
  'on:',
  '  schedule:',
  '    - cron: \'17 9 */3 * *\'',
  '  workflow_dispatch:',
  'permissions: {}',
  'jobs:',
  '  ping:',
  '    runs-on: ubuntu-latest',
  '    timeout-minutes: 5',
  '    steps:',
  '      - run: curl -fsS "${{ vars.SUPABASE_URL }}/rest/v1/published_documents?select=id&limit=1" -H "apikey: ${{ vars.SUPABASE_PUBLISHABLE_KEY }}" -H "Authorization: Bearer ${{ vars.SUPABASE_PUBLISHABLE_KEY }}"',
  ''
].join('\n')

/**
 * @typedef {{ file: string, status: 'added' | 'updated' | 'same' | 'kept' }} KeepaliveChangeType
 */

/**
 * Writes the keepalive workflow where none exists and rewrites one the package wrote; a file without the marker
 * belongs to the project and is kept.
 * @param {{ root: string, write?: boolean }} options
 * @returns {Promise<KeepaliveChangeType>}
 */
export const syncKeepalive = async ({ root, write = true }) => {
  const path = join(root, KEEPALIVE_FILE)
  const wanted = keepaliveWorkflow()
  const current = existsSync(path) ? await readFile(path, 'utf8') : null
  if (current === wanted) return { file: KEEPALIVE_FILE, status: 'same' }
  if (current !== null && !current.startsWith(KEEPALIVE_MARKER)) return { file: KEEPALIVE_FILE, status: 'kept' }
  if (write) {
    await mkdir(dirname(path), { recursive: true })
    await writeFile(path, wanted)
  }
  return { file: KEEPALIVE_FILE, status: current === null ? 'added' : 'updated' }
}
